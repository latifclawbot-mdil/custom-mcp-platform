#!/usr/bin/env python3
"""Regenerate docs/integrity-manifest.json from the vendored server trees.

Why this exists
---------------
The vendored ``servers/<name>/`` trees are copies of files that live in two
upstream repositories this project does not own. The earlier version of the
integrity test hashed the vendored files against the *originals on the machine
that happened to have them* — an absolute path to a sibling checkout on the
authoring host. That test could not run in a clean clone: it either skipped
(proving nothing) or failed on a different host. It also made the test's truth
depend on mutable local state rather than on what this repository actually
ships.

This script freezes the expected content into ``docs/integrity-manifest.json``:
a committed map of ``path -> sha256`` for every vendored file, computed from the
committed trees at the recorded upstream HEAD. The test then verifies the
working tree against that manifest, which is hermetic — it needs nothing but
this repository, so it runs identically in a fresh ``git clone`` with no
originals present anywhere.

Usage
-----
    python scripts/gen_integrity_manifest.py [--check]

Without ``--check`` it rewrites the manifest. With ``--check`` it recomputes
and exits non-zero if the committed manifest disagrees with the current trees
(same logic the test uses, usable from CI before pytest is installed).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MANIFEST = REPO / "docs" / "integrity-manifest.json"

#: Upstream HEAD each vendored tree was copied from. Recorded so a reader can
#: tell *which* revision `file -> sha256` describes without network access.
UPSTREAM_HEAD = {
    "play-console": "74d2d2f6438a940307a0c7855bc3842df7a91a72",
    "search-console": "06aa911e8c82e30731dad454324b0df455ff73a8",
}

#: Files this platform adds to the vendored tree; they are not upstream content
#: and are therefore excluded from the manifest (they are covered by the
#: platform's own tests instead).
PLATFORM_ADDED = {
    "play-console": ["src/play_console_mcp/http_main.py"],
    "search-console": ["src/search_console_mcp/http_main.py"],
}

#: Never hashed: build/test byproducts, VCS state, and virtualenvs.
EXCLUDE_PARTS = {"__pycache__", ".pytest_cache", ".git", ".venv"}

#: Metadata the manifest also records, so a diff is self-describing.
_COMMENT = (
    "Hermetic integrity manifest for the vendored server trees. Generated by "
    "scripts/gen_integrity_manifest.py; do not hand-edit. Excludes the "
    "platform-added http_main.py and any cache byproduct."
)


def _iter_hashed(server: str) -> dict[str, str]:
    """Return ``relative/path -> sha256`` for one vendored tree."""
    root = REPO / "servers" / server
    if not root.is_dir():
        raise SystemExit(f"vendored tree missing: {root}")
    added = set(PLATFORM_ADDED.get(server, []))
    files: dict[str, str] = {}
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        if any(part in EXCLUDE_PARTS for part in path.parts):
            continue
        if relative.endswith(".pyc") or "egg-info" in relative:
            continue
        if relative in added:
            continue
        files[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    return files


def build() -> dict:
    manifest = {
        "_comment": _COMMENT,
        "covers": (
            "servers/<name>/ committed source copied from the upstream "
            "google-operations-mcp repositories at the recorded HEAD"
        ),
        "servers": {},
    }
    for server, head in sorted(UPSTREAM_HEAD.items()):
        files = _iter_hashed(server)
        manifest["servers"][server] = {
            "upstream_repo": f"google-operations-mcp/{server}",
            "upstream_head": head,
            "platform_added_files": sorted(PLATFORM_ADDED.get(server, [])),
            "file_count": len(files),
            "files": files,
        }
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed manifest matches the trees; do not write",
    )
    args = parser.parse_args(argv)

    fresh = build()
    if args.check:
        if not MANIFEST.exists():
            print(f"missing manifest: {MANIFEST}", file=sys.stderr)
            return 1
        committed = json.loads(MANIFEST.read_text(encoding="utf-8"))
        if committed != fresh:
            print("integrity manifest is stale or the trees changed:", file=sys.stderr)
            for server, block in fresh["servers"].items():
                old = committed.get("servers", {}).get(server, {})
                added = {k: v for k, v in block["files"].items() if old.get("files", {}).get(k) != v}
                removed = {k: v for k, v in old.get("files", {}).items() if k not in block["files"]}
                if added or removed:
                    print(f"  {server}: changed={sorted(added)} removed={sorted(removed)}", file=sys.stderr)
            return 1
        total = sum(block["file_count"] for block in fresh["servers"].values())
        print(f"integrity manifest OK ({total} files across {len(fresh['servers'])} servers)")
        return 0

    MANIFEST.write_text(json.dumps(fresh, indent=2) + "\n", encoding="utf-8")
    total = sum(block["file_count"] for block in fresh["servers"].values())
    print(f"wrote {MANIFEST.relative_to(REPO)} ({total} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())